"""PostgreSQL connection, schema initialization, and one-time SQLite import."""
from __future__ import annotations

import os
import sqlite3
import threading
from contextlib import closing
from pathlib import Path
from typing import Any, TYPE_CHECKING

if TYPE_CHECKING:
    import psycopg

_DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
_DATA_DIR = Path(__file__).resolve().parents[2] / "data"
_SCHEMA_LOCK = threading.RLock()


def _create_schema(connection: Any) -> None:
    connection.execute("""
        CREATE TABLE IF NOT EXISTS signal_history (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            signal_date TEXT NOT NULL,
            captured_at TEXT NOT NULL,
            symbol TEXT NOT NULL,
            strategy TEXT NOT NULL,
            strategy_title TEXT NOT NULL,
            entry_price DOUBLE PRECISION NOT NULL,
            stop_loss DOUBLE PRECISION NOT NULL,
            target_1 DOUBLE PRECISION NOT NULL,
            target_2 DOUBLE PRECISION,
            risk_reward DOUBLE PRECISION,
            confidence_score DOUBLE PRECISION,
            overall_score DOUBLE PRECISION,
            max_holding_days INTEGER NOT NULL CHECK(max_holding_days IN (15, 30)),
            outcome TEXT NOT NULL DEFAULT 'OPEN',
            exit_date TEXT,
            exit_price DOUBLE PRECISION,
            holding_sessions INTEGER NOT NULL DEFAULT 0,
            last_price DOUBLE PRECISION,
            last_checked_date TEXT,
            snapshot_json TEXT NOT NULL,
            UNIQUE(signal_date, symbol, strategy)
        )
    """)
    connection.execute("CREATE INDEX IF NOT EXISTS idx_signal_history_date ON signal_history(signal_date DESC)")
    connection.execute("""
        CREATE TABLE IF NOT EXISTS manual_portfolio (
            symbol TEXT PRIMARY KEY,
            quantity DOUBLE PRECISION NOT NULL CHECK(quantity > 0),
            average_price DOUBLE PRECISION NOT NULL CHECK(average_price > 0),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)
    connection.execute("""
        CREATE TABLE IF NOT EXISTS marketvoice_migrations (
            name TEXT PRIMARY KEY,
            applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)


def _sqlite_table_exists(connection: sqlite3.Connection, table_name: str) -> bool:
    return connection.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table_name,)
    ).fetchone() is not None


def _migrate_legacy_sqlite(connection: Any) -> None:
    legacy_sources = (
        (_DATA_DIR / "marketvoice_history.sqlite3", "signal_history"),
        (_DATA_DIR / "marketvoice_portfolio.sqlite3", "manual_portfolio"),
    )
    for path, table in legacy_sources:
        migration_name = f"sqlite-import:{path.name}"
        already_done = connection.execute(
            "SELECT 1 FROM marketvoice_migrations WHERE name = %s", (migration_name,)
        ).fetchone()
        if already_done:
            continue

        if path.exists():
            with closing(sqlite3.connect(path)) as legacy:
                legacy.row_factory = sqlite3.Row
                if _sqlite_table_exists(legacy, table):
                    rows = legacy.execute(f"SELECT * FROM {table}").fetchall()
                    if table == "signal_history" and rows:
                        columns = (
                            "signal_date, captured_at, symbol, strategy, strategy_title, entry_price, "
                            "stop_loss, target_1, target_2, risk_reward, confidence_score, overall_score, "
                            "max_holding_days, outcome, exit_date, exit_price, holding_sessions, last_price, "
                            "last_checked_date, snapshot_json"
                        )
                        placeholders = ", ".join(["%s"] * 20)
                        with connection.cursor() as cursor:
                            for row in rows:
                                cursor.execute(
                                    f"INSERT INTO signal_history ({columns}) VALUES ({placeholders}) "
                                    "ON CONFLICT (signal_date, symbol, strategy) DO NOTHING",
                                    tuple(row[column] for column in columns.replace(" ", "").split(",")),
                                )
                    elif table == "manual_portfolio" and rows:
                        with connection.cursor() as cursor:
                            for row in rows:
                                cursor.execute(
                                    "INSERT INTO manual_portfolio (symbol, quantity, average_price) VALUES (%s, %s, %s) "
                                    "ON CONFLICT (symbol) DO NOTHING",
                                    (row["symbol"], row["quantity"], row["average_price"]),
                                )
        connection.execute(
            "INSERT INTO marketvoice_migrations (name) VALUES (%s) ON CONFLICT (name) DO NOTHING",
            (migration_name,),
        )


def get_connection() -> Any:
    """Open a configured PostgreSQL connection and ensure the app schema exists."""
    if not _DATABASE_URL:
        raise RuntimeError("PostgreSQL is not configured. Set DATABASE_URL in backend/.env.")
    try:
        import psycopg
        from psycopg.rows import dict_row
    except ImportError as exc:
        raise RuntimeError(
            "The PostgreSQL driver is missing. Install backend/requirements.txt first."
        ) from exc
    connection = psycopg.connect(_DATABASE_URL, connect_timeout=5, row_factory=dict_row)
    try:
        with _SCHEMA_LOCK:
            _create_schema(connection)
            _migrate_legacy_sqlite(connection)
        return connection
    except Exception:
        connection.close()
        raise
